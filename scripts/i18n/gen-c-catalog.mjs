#!/usr/bin/env node
/*
 * WebHack i18n — bake the translated message catalog into a C header
 * (src/nhi18n_catalog.h) that src/nhi18n.c compiles in. This avoids a runtime
 * JSON parser: the catalog is a static array of {msgid, msgstr} pairs.
 *
 * Correctness notes (critical):
 *  - The RUNTIME msgid is the C-*interpreted* string: `_("a\n")` passes the
 *    bytes a,<LF>. Our translations.json stores the *source* form (backslash-n
 *    as two chars, preserved by the extractor). So we UNESCAPE C escapes here to
 *    get the true runtime bytes, then re-emit them as a C literal.
 *  - Emission uses 3-digit OCTAL for every byte that isn't plain-safe ASCII, so
 *    the generated literals are valid-by-construction (no greedy-hex issues, no
 *    stray quotes/backslashes, UTF-8 bytes emitted as \ooo).
 *
 * Data-only (produces a header; the C build is separate). Usage:
 *   node scripts/i18n/gen-c-catalog.mjs [lang=zh-CN]
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const lang = process.argv[2] || 'zh-CN';
const cId = lang.replace(/[^A-Za-z0-9]/g, '_'); // zh-CN -> zh_CN

const translations = JSON.parse(
  fs.readFileSync(path.join(repoRoot, 'locales', lang, 'webhack.translations.json'), 'utf8')
);

// Interpret C escape sequences in a source-form string into its true bytes
// (returned as a Node Buffer of UTF-8 bytes).
function unescapeC(s) {
  let out = '';
  for (let i = 0; i < s.length; i++) {
    if (s[i] !== '\\') { out += s[i]; continue; }
    const c = s[++i];
    switch (c) {
      case 'n': out += '\n'; break;
      case 't': out += '\t'; break;
      case 'r': out += '\r'; break;
      case 'f': out += '\f'; break;
      case 'b': out += '\b'; break;
      case 'v': out += '\v'; break;
      case 'a': out += '\x07'; break;
      case '"': out += '"'; break;
      case '\\': out += '\\'; break;
      case "'": out += "'"; break;
      case '0': out += '\0'; break;
      default: out += (c === undefined ? '' : c); break; // unknown: drop backslash
    }
  }
  return Buffer.from(out, 'utf8');
}

// Emit a Buffer as a valid C string literal body using octal for unsafe bytes.
function cLiteral(buf) {
  let out = '';
  for (const b of buf) {
    if (b >= 0x20 && b <= 0x7e && b !== 0x22 /* " */ && b !== 0x5c /* \ */) {
      out += String.fromCharCode(b);
    } else {
      out += '\\' + b.toString(8).padStart(3, '0');
    }
  }
  return out;
}

// Build entries, sorted by the true msgid bytes. An EMPTY-STRING translation is
// meaningful, not a gap: it means "zh drops this English word" (articles a/the,
// auxiliaries have/are, ordinal suffixes st/nd/th, honorifics Mr./Ms.). It MUST
// be emitted so _(word) returns "" instead of falling back to the English key
// (nhi18n_gettext returns `tr ? tr : msgid`). Only skip non-strings.
const entries = [];
for (const [msgid, msgstr] of Object.entries(translations)) {
  if (typeof msgstr !== 'string') continue;
  entries.push({ key: unescapeC(msgid), val: unescapeC(msgstr) });
}
entries.sort((a, b) => Buffer.compare(a.key, b.key));

const lines = [];
lines.push('/* AUTO-GENERATED by scripts/i18n/gen-c-catalog.mjs -- DO NOT EDIT. */');
lines.push(`/* Message catalog for ${lang}: ${entries.length} entries. */`);
lines.push('');
lines.push('struct nhi18n_entry { const char *id; const char *str; };');
lines.push('');
lines.push(`static const struct nhi18n_entry nhi18n_catalog_${cId}[] = {`);
for (const e of entries) {
  lines.push(`    { "${cLiteral(e.key)}", "${cLiteral(e.val)}" },`);
}
lines.push('};');
lines.push(`static const int nhi18n_catalog_${cId}_count =`);
lines.push(`    (int) (sizeof nhi18n_catalog_${cId} / sizeof nhi18n_catalog_${cId}[0]);`);
lines.push('');

const outPath = path.join(repoRoot, 'src', 'nhi18n_catalog.h');
fs.writeFileSync(outPath, lines.join('\n'));
const kb = (fs.statSync(outPath).size / 1024).toFixed(0);
console.log(`generated src/nhi18n_catalog.h: ${entries.length} entries, ${kb} KB`);
