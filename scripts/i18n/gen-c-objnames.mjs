#!/usr/bin/env node
/*
 * WebHack i18n — generate src/nhi18n_objnames.h
 *
 * Emits nhi18n_objname_zh(int otyp): a switch over the ONAME constants (from
 * include/onames.h) returning the octal-escaped UTF-8 Chinese object base name,
 * or NULL for objects we don't translate. Keying on the ONAME symbols is
 * correct-by-construction (the compiler resolves each to the right index), so
 * this can never drift out of sync with onames.h numbering.
 *
 * Only keys that actually exist in onames.h are emitted; anything else is
 * dropped and reported (so a stale key can't break the build). The '_comment'
 * meta key in the JSON is ignored.
 *
 * Usage: node scripts/i18n/gen-c-objnames.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const onamesPath = path.join(repoRoot, 'include', 'onames.h');
const namesPath = path.join(repoRoot, 'webhack-client', 'public', 'data', 'object-names.zh-CN.json');
const outPath = path.join(repoRoot, 'src', 'nhi18n_objnames.h');

// Valid ONAME symbols from onames.h (#define NAME value).
const onamesSrc = fs.readFileSync(onamesPath, 'utf8');
const valid = new Set([...onamesSrc.matchAll(/^#define\s+([A-Z][A-Z0-9_]*)\b/gm)].map(m => m[1]));

const names = JSON.parse(fs.readFileSync(namesPath, 'utf8'));

function octal(str) {
  const bytes = Buffer.from(str, 'utf8');
  let out = '';
  for (const b of bytes) out += '\\' + b.toString(8).padStart(3, '0');
  return out;
}

// Some objects (the 9 "worthless piece of X glass" gems) have their ONAME
// #define COMMENTED OUT in onames.h, so the symbol is undefined in C and we
// can't emit `case <SYMBOL>:`. makedefs still assigns them a stable otyp, which
// the comment preserves: `/* #define WORTHLESS_PIECE_OF_WHITE_GLASS 433 */`.
// Harvest those so we can emit `case <number>:` for them instead.
const commentedVal = {};
for (const m of onamesSrc.matchAll(/\/\*\s*#define\s+([A-Z][A-Z0-9_]*)\s+(\d+)\s*\*\//g))
  commentedVal[m[1]] = +m[2];

const emitted = [], dropped = [];
for (const [oname, zh] of Object.entries(names)) {
  if (oname === '_comment') continue;
  if (valid.has(oname)) emitted.push([oname, zh]);            // case SYMBOL:
  else if (oname in commentedVal) emitted.push([commentedVal[oname], zh, oname]); // case <num>: /* SYMBOL */
  else { dropped.push(oname); continue; }
}

let out = `/* WebHack   nhi18n_objnames.h -- GENERATED by scripts/i18n/gen-c-objnames.mjs */
/* zh-CN object base names, keyed on the ONAME constants (include/onames.h). Do not edit. */

static const char *
nhi18n_objname_zh(otyp)
int otyp;
{
    switch (otyp) {
`;
for (const [key, zh, sym] of emitted) {
  const label = sym ? `${key} /* ${sym} */` : key;
  out += `    case ${label}: return "${octal(zh)}"; /* ${zh} */\n`;
}
out += `    default: return (const char *) 0;
    }
}

/*nhi18n_objnames.h*/
`;

fs.writeFileSync(outPath, out);
console.log(`Wrote ${path.relative(repoRoot, outPath)}: ${emitted.length} names`);
if (dropped.length) console.log(`Dropped (not in onames.h): ${dropped.join(', ')}`);
