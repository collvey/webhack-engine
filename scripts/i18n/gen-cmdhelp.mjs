const arc = readDlb('sys/wasm/nhdat');
const src = arc.entries.find((e) => e.fname === 'cmdhelp').data.toString('utf8');
const missing = new Set();
const out = src.split('\n').map((line) => {
  const ti = line.indexOf('\t');
  if (ti < 0) return line; // directive/comment/blank -> verbatim
  const key = line.slice(0, ti);
  const desc = line.slice(ti + 1);
  if (desc === '') return line;
  if (!(desc in DICT)) { missing.add(desc); return line; }
  return key + '\t' + DICT[desc];
}).join('\n');

if (missing.size) {
  console.error('MISSING translations:', missing.size);
  [...missing].forEach((d) => console.error('  ' + JSON.stringify(d)));
  process.exit(1);
}
fs.writeFileSync('locales/zh-CN/dat/cmdhelp.txt', out);
console.log('wrote locales/zh-CN/dat/cmdhelp.txt (' + Buffer.byteLength(out) + ' bytes)');
