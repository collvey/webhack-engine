#!/usr/bin/env node
/*
 * WebHack i18n — generate src/nhi18n_monnames.h
 *
 * Emits nhi18n_monname_zh(int mnum): a switch over the PM_* enum constants
 * (from include/pm.h) returning the octal-escaped UTF-8 Chinese monster name,
 * or NULL for monsters we don't translate. Keying on PM_* symbols is
 * correct-by-construction: the compiler resolves each case to the right index,
 * so this can never drift out of sync with pm.h numbering.
 *
 * Only PM_* keys that actually exist in pm.h's `enum monnums` are emitted;
 * anything else is dropped and reported (so a stale name can't break the build).
 *
 * Usage: node scripts/i18n/gen-c-monnames.mjs
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repoRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const pmPath = path.join(repoRoot, 'include', 'pm.h');
const namesPath = path.join(repoRoot, 'webhack-client', 'public', 'data', 'monster-names.zh-CN.json');
const outPath = path.join(repoRoot, 'src', 'nhi18n_monnames.h');

// Valid PM_* symbols = those defined in `enum monnums { ... }`.
const pmSrc = fs.readFileSync(pmPath, 'utf8');
const enumBody = pmSrc.slice(pmSrc.indexOf('enum monnums'));
const validPM = new Set([...enumBody.matchAll(/\b(PM_[A-Z0-9_]+)\s*=/g)].map(m => m[1]));

const names = JSON.parse(fs.readFileSync(namesPath, 'utf8'));

// Octal-escape every byte of the UTF-8 string so the C literal is portable and
// never confuses the compiler's charset handling (matches nhi18n_catalog.h).
function octal(str) {
  const bytes = Buffer.from(str, 'utf8');
  let out = '';
  for (const b of bytes) out += '\\' + b.toString(8).padStart(3, '0');
  return out;
}

const emitted = [];
const dropped = [];
for (const [pm, zh] of Object.entries(names)) {
  if (!validPM.has(pm)) { dropped.push(pm); continue; }
  emitted.push([pm, zh]);
}

let out = `/* WebHack   nhi18n_monnames.h -- GENERATED by scripts/i18n/gen-c-monnames.mjs */
/* zh-CN monster base names, keyed on the PM_* enum (include/pm.h). Do not edit. */

static const char *
nhi18n_monname_zh(mnum)
int mnum;
{
    switch (mnum) {
`;
for (const [pm, zh] of emitted) {
  out += `    case ${pm}: return "${octal(zh)}"; /* ${zh} */\n`;
}
out += `    default: return (const char *) 0;
    }
}

/*nhi18n_monnames.h*/
`;

fs.writeFileSync(outPath, out);
console.log(`Wrote ${path.relative(repoRoot, outPath)}: ${emitted.length} names`);
if (dropped.length) console.log(`Dropped (not in pm.h enum): ${dropped.join(', ')}`);
