#!/usr/bin/env python3
"""
Extract all object definitions from onames.h (generated by makedefs)
This is the authoritative source for object IDs and names.
"""

import re
import json

def convert_name(constant_name):
    """Convert CONSTANT_NAME to readable name."""
    # Skip artifact names (ART_*) - they're not regular objects
    if constant_name.startswith('ART_'):
        return None
    
    # Remove prefixes
    name = constant_name
    prefixes = ['POT_', 'SCR_', 'SPE_', 'WAN_', 'RIN_', 'AMULET_OF_', 'AMULET_VERSUS_']
    for prefix in prefixes:
        if name.startswith(prefix):
            name = name[len(prefix):]
            break
    
    # Convert underscores to spaces and lowercase
    name = name.replace('_', ' ').lower()
    
    # Capitalize first letter of each word
    name = ' '.join(word.capitalize() if word not in ['of', 'the'] else word 
                   for word in name.split())
    
    return name

def determine_symbol_and_class(obj_id, name):
    """Determine the symbol and class based on ID ranges."""
    
    # Based on objclass.h enum and object ordering in objects.c
    if obj_id == 0:
        return ('?', 'strange')
    elif obj_id >= 1 and obj_id <= 70:  # Weapons
        return (')', 'weapon')
    elif obj_id >= 71 and obj_id <= 157:  # Armor
        return ('[', 'armor')
    elif obj_id >= 158 and obj_id <= 181:  # Rings
        return ('=', 'ring')
    elif obj_id >= 182 and obj_id <= 191:  # Amulets
        return ('"', 'amulet')
    elif obj_id >= 192 and obj_id <= 230:  # Tools
        return ('(', 'tool')
    elif obj_id >= 231 and obj_id <= 271:  # Food
        return ('%', 'food')
    elif obj_id >= 272 and obj_id <= 297:  # Potions
        return ('!', 'potion')
    elif obj_id >= 298 and obj_id <= 339:  # Scrolls
        return ('?', 'scroll')
    elif obj_id >= 340 and obj_id <= 390:  # Spellbooks
        return ('+', 'spellbook')
    elif obj_id >= 391 and obj_id <= 417:  # Wands
        return ('/', 'wand')
    elif obj_id == 418:  # Gold
        return ('$', 'coin')
    elif obj_id >= 419 and obj_id <= 450:  # Gems
        return ('*', 'gem')
    elif obj_id >= 451 and obj_id <= 452:  # Rocks (boulder, statue)
        return ('`', 'rock')
    elif obj_id == 453:  # Heavy iron ball
        return ('0', 'ball')
    elif obj_id == 454:  # Iron chain
        return ('_', 'chain')
    elif obj_id >= 455 and obj_id <= 456:  # Venom
        return ('.', 'venom')
    else:
        return ('?', 'unknown')

def extract_from_onames():
    """Extract all object definitions from onames.h."""
    
    with open('../include/onames.h', 'r', encoding='utf-8') as f:
        content = f.read()
    
    objects_dict = {}
    
    # Pattern to match #define OBJECT_NAME ID
    pattern = r'#define\s+([A-Z_]+)\s+(\d+)'
    
    for match in re.finditer(pattern, content):
        constant_name = match.group(1)
        obj_id = int(match.group(2))
        
        # Skip special constants
        if constant_name in ['NUM_OBJECTS', 'LAST_GEM', 'MAXSPELL']:
            continue
        
        # Convert name
        readable_name = convert_name(constant_name)
        
        # Skip if name is None (artifacts)
        if readable_name is None:
            continue
        
        # Determine symbol and class
        symbol, obj_class = determine_symbol_and_class(obj_id, readable_name)
        
        # Add description
        description = generate_description(readable_name, obj_class)
        
        objects_dict[str(obj_id)] = {
            'name': readable_name,
            'symbol': symbol,
            'description': description
        }
    
    return objects_dict

def generate_description(name, obj_class):
    """Generate a description for an object."""
    
    custom_descriptions = {
        'gain ability': 'Increases random ability score',
        'restore ability': 'Restores drained abilities',
        'confusion': 'Causes confusion',
        'blindness': 'Causes temporary blindness',
        'paralysis': 'Paralyzes you',
        'speed': 'Increases movement speed',
        'levitation': 'Float above ground',
        'hallucination': 'Causes hallucinations',
        'invisibility': 'Makes you invisible',
        'see invisible': 'Reveals invisible creatures',
        'healing': 'Restores health',
        'extra healing': 'Greatly restores health',
        'full healing': 'Fully restores health',
        'gain level': 'Increases experience level',
        'gain energy': 'Increases magical energy',
        'water': 'Clear liquid',
        'oil': 'Flammable liquid',
        'acid': 'Corrosive liquid',
        # Add more as needed
    }
    
    if name in custom_descriptions:
        return custom_descriptions[name]
    
    # Generic descriptions by class
    if obj_class == 'potion':
        return f'Potion of {name}'
    elif obj_class == 'scroll':
        return f'Scroll of {name}'
    elif obj_class == 'spellbook':
        return f'Spellbook of {name}'
    elif obj_class == 'wand':
        return f'Wand of {name}'
    elif obj_class == 'ring':
        return f'Ring of {name}'
    elif obj_class == 'amulet':
        return name
    else:
        return name

def main():
    print("Extracting objects from onames.h...")
    
    objects_dict = extract_from_onames()
    
    print(f"Found {len(objects_dict)} objects")
    
    # Show samples
    print("\nSample objects:")
    for obj_id in ['1', '17', '282', '283', '340', '391']:
        if obj_id in objects_dict:
            obj = objects_dict[obj_id]
            print(f"  {obj_id}: {obj['name']} ({obj['symbol']}) - {obj['description']}")
    
    # Write to items.json
    output_file = '../webhack-client/public/data/items.json'
    with open(output_file, 'w', encoding='utf-8') as f:
        json.dump(objects_dict, f, indent=2, ensure_ascii=False)
    
    print(f"\nWrote {len(objects_dict)} items to {output_file}")
    
    # Show potion IDs
    potions = {k: v for k, v in objects_dict.items() if v['symbol'] == '!'}
    print(f"\nFound {len(potions)} potions (IDs 272-297):")
    for obj_id in sorted(potions.keys(), key=int)[:10]:
        obj = potions[obj_id]
        print(f"  {obj_id}: {obj['name']}")

if __name__ == '__main__':
    main()
